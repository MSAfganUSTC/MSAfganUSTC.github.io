(function () {
  "use strict";

  /*
   * Dynamic CV generator.
   *
   * The PDF is built from the currently rendered one-page CV, so website edits
   * are reflected automatically. It uses text-based jsPDF output and embeds
   * the profile/reference photographs directly into the PDF.
   */

  const JSPDF_URL = "https://cdn.jsdelivr.net/npm/jspdf@2.5.1/dist/jspdf.umd.min.js";
  const PDF_FILENAME = "Muhammad_Sher_Afgan_CV.pdf";
  const imageCache = new Map();
  let libraryPromise = null;
  let generating = false;

  function setStatus(message) {
    const status = document.getElementById("cv-download-status");
    if (status) status.textContent = message || "";
  }

  function loadJsPdf() {
    if (window.jspdf && window.jspdf.jsPDF) {
      return Promise.resolve(window.jspdf.jsPDF);
    }
    if (libraryPromise) return libraryPromise;

    libraryPromise = new Promise(function (resolve, reject) {
      const script = document.createElement("script");
      script.src = JSPDF_URL;
      script.async = true;
      script.onload = function () {
        if (window.jspdf && window.jspdf.jsPDF) resolve(window.jspdf.jsPDF);
        else reject(new Error("jsPDF loaded but was not initialized."));
      };
      script.onerror = function () {
        reject(new Error("Unable to load the PDF generator."));
      };
      document.head.appendChild(script);
    });

    return libraryPromise;
  }

  function cleanText(value) {
    return String(value || "")
      .replace(/\u00a0/g, " ")
      .replace(/[ \t]+/g, " ")
      .replace(/\s*\n\s*/g, " ")
      .trim();
  }

  function nodeText(node) {
    if (!node) return "";
    return cleanText(node.textContent || "");
  }

  async function getOriginalCvSource() {
    /*
     * Google Translate rewrites the live DOM in the selected language. jsPDF's
     * built-in Helvetica font is Latin-only, so reading translated Chinese,
     * Japanese, Arabic, etc. from the live page produces corrupted glyphs.
     *
     * Fetch the original same-origin HTML from GitHub Pages instead. That HTML
     * is always the canonical English source generated by Jekyll, independent
     * of the visitor's current Google Translate selection.
     */
    try {
      const url = new URL(window.location.href);
      url.hash = "";
      const response = await fetch(url.href, {
        cache: "no-store",
        credentials: "same-origin"
      });
      if (!response.ok) throw new Error("HTTP " + response.status);
      const html = await response.text();
      const parsed = new DOMParser().parseFromString(html, "text/html");
      const source = parsed.getElementById("cv-content");
      if (source) return source;
    } catch (error) {
      console.warn("Unable to load canonical English CV source; using current page.", error);
    }

    return document.getElementById("cv-content");
  }

  function loadHtmlImage(src) {
    return new Promise(function (resolve, reject) {
      const image = new Image();
      image.decoding = "async";
      image.onload = function () { resolve(image); };
      image.onerror = function () { reject(new Error("Unable to decode image: " + src)); };
      image.src = src;
    });
  }

  function imageToJpegDataUrl(image) {
    const naturalWidth = image.naturalWidth || image.width || 1;
    const naturalHeight = image.naturalHeight || image.height || 1;
    const maxDimension = 1400;
    const scale = Math.min(1, maxDimension / Math.max(naturalWidth, naturalHeight));
    const width = Math.max(1, Math.round(naturalWidth * scale));
    const height = Math.max(1, Math.round(naturalHeight * scale));

    const canvas = document.createElement("canvas");
    canvas.width = width;
    canvas.height = height;
    const context = canvas.getContext("2d", { alpha: false });
    if (!context) throw new Error("Canvas is unavailable for PDF image conversion.");

    context.fillStyle = "#ffffff";
    context.fillRect(0, 0, width, height);
    context.drawImage(image, 0, 0, width, height);
    return canvas.toDataURL("image/jpeg", 0.92);
  }

  async function loadImageData(src) {
    if (!src) return null;
    const absoluteUrl = new URL(src, window.location.href).href;
    if (imageCache.has(absoluteUrl)) return imageCache.get(absoluteUrl);

    const promise = (async function () {
      try {
        /*
         * Fetch the same-origin website image first, decode it in the browser,
         * then rasterize it to a standard JPEG data URL. This avoids jsPDF
         * browser-specific PNG/JPEG decoding issues and reliably embeds the
         * profile/reference photographs in the downloaded PDF.
         */
        const response = await fetch(absoluteUrl, {
          cache: "no-cache",
          credentials: "same-origin"
        });
        if (!response.ok) throw new Error("HTTP " + response.status);

        const blob = await response.blob();
        const objectUrl = URL.createObjectURL(blob);
        try {
          const image = await loadHtmlImage(objectUrl);
          return imageToJpegDataUrl(image);
        } finally {
          URL.revokeObjectURL(objectUrl);
        }
      } catch (firstError) {
        /* Fallback for browsers that reject blob decoding for a cached asset. */
        try {
          const image = await loadHtmlImage(absoluteUrl);
          return imageToJpegDataUrl(image);
        } catch (secondError) {
          console.warn("Unable to prepare PDF image:", absoluteUrl, firstError, secondError);
          return null;
        }
      }
    })();

    imageCache.set(absoluteUrl, promise);
    return promise;
  }

  function createPdfWriter(jsPDF) {
    const doc = new jsPDF({ unit: "pt", format: "a4", orientation: "portrait" });
    const pageWidth = doc.internal.pageSize.getWidth();
    const pageHeight = doc.internal.pageSize.getHeight();
    const marginX = 44;
    const marginTop = 44;
    const marginBottom = 46;
    const contentWidth = pageWidth - (marginX * 2);
    let y = marginTop;

    function addPage() {
      doc.addPage();
      y = marginTop;
    }

    function ensureSpace(height) {
      if (y + height > pageHeight - marginBottom) addPage();
    }

    function font(style, size, color) {
      doc.setFont("helvetica", style || "normal");
      doc.setFontSize(size || 9.5);
      doc.setTextColor.apply(doc, color || [40, 40, 40]);
    }

    function getImageFit(dataUrl, maxWidth, maxHeight) {
      let width = maxWidth;
      let height = maxHeight;
      try {
        const properties = doc.getImageProperties(dataUrl);
        const ratio = properties.width / properties.height;
        width = maxWidth;
        height = width / ratio;
        if (height > maxHeight) {
          height = maxHeight;
          width = height * ratio;
        }
      } catch (error) {
        // Keep the fallback box size if image metadata cannot be read.
      }
      return { width: width, height: height };
    }

    function addImageFit(dataUrl, x, top, maxWidth, maxHeight) {
      if (!dataUrl) return { width: 0, height: 0 };
      const fit = getImageFit(dataUrl, maxWidth, maxHeight);
      try {
        doc.addImage(dataUrl, "JPEG", x, top, fit.width, fit.height, undefined, "MEDIUM");
      } catch (error) {
        console.warn("Unable to add an image to the PDF.", error);
        return { width: 0, height: 0 };
      }
      return fit;
    }

    function writeHeader(name, bio, contact, profileImage) {
      const hasPhoto = Boolean(profileImage);
      const photoMaxWidth = 76;
      const photoMaxHeight = 92;
      const gap = 16;
      const textWidth = hasPhoto ? contentWidth - photoMaxWidth - gap : contentWidth;

      font("bold", 20, [45, 49, 52]);
      const nameLines = doc.splitTextToSize(cleanText(name), textWidth);
      font("normal", 10.5, [70, 74, 78]);
      const bioLines = bio ? doc.splitTextToSize(cleanText(bio), textWidth) : [];
      font("normal", 9.2, [75, 79, 82]);
      const contactLines = contact ? doc.splitTextToSize(cleanText(contact), textWidth) : [];

      const textHeight = (nameLines.length * 23) + (bioLines.length * 14) + (contactLines.length * 12) + 8;
      const blockHeight = Math.max(textHeight, hasPhoto ? photoMaxHeight : 0);
      ensureSpace(blockHeight + 28);

      const startY = y;
      if (hasPhoto) {
        const fit = getImageFit(profileImage, photoMaxWidth, photoMaxHeight);
        const imageX = pageWidth - marginX - fit.width;
        addImageFit(profileImage, imageX, startY, photoMaxWidth, photoMaxHeight);

        font("bold", 20, [45, 49, 52]);
        doc.text(nameLines, marginX, y);
        y += nameLines.length * 23;

        if (bioLines.length) {
          font("normal", 10.5, [70, 74, 78]);
          doc.text(bioLines, marginX, y);
          y += bioLines.length * 14;
        }

        if (contactLines.length) {
          font("normal", 9.2, [75, 79, 82]);
          doc.text(contactLines, marginX, y);
          y += contactLines.length * 12;
        }

        y = Math.max(y, startY + fit.height);
      } else {
        font("bold", 20, [45, 49, 52]);
        doc.text(nameLines, pageWidth / 2, y, { align: "center" });
        y += nameLines.length * 23;

        if (bioLines.length) {
          font("normal", 10.5, [70, 74, 78]);
          doc.text(bioLines, pageWidth / 2, y, { align: "center" });
          y += bioLines.length * 14;
        }

        if (contactLines.length) {
          font("normal", 9.2, [75, 79, 82]);
          doc.text(contactLines, pageWidth / 2, y, { align: "center" });
          y += contactLines.length * 12;
        }
      }

      y += 10;
      doc.setDrawColor(210, 210, 210);
      doc.line(marginX, y, pageWidth - marginX, y);
      y += 18;
    }

    function writeSectionHeading(text) {
      const title = cleanText(text);
      if (!title) return;
      const boxHeight = 31;
      ensureSpace(boxHeight + 12);
      doc.setFillColor(244, 244, 244);
      doc.roundedRect(marginX, y, contentWidth, boxHeight, 4, 4, "F");
      doc.setFillColor(89, 97, 104);
      doc.rect(marginX, y, 4, boxHeight, "F");
      font("bold", 13.2, [76, 82, 87]);
      doc.text(title, marginX + 15, y + 20.5);
      y += boxHeight + 13;
    }

    function writeSubHeading(text, level) {
      const value = cleanText(text);
      if (!value) return;
      const size = level === 2 ? 11.7 : 10.3;
      const lineHeight = level === 2 ? 15 : 13;
      font("bold", size, [52, 56, 60]);
      const lines = doc.splitTextToSize(value, contentWidth);
      ensureSpace(lines.length * lineHeight + 8);
      doc.text(lines, marginX, y);
      y += lines.length * lineHeight + (level === 2 ? 5 : 4);
    }

    function writeParagraph(text, options) {
      const value = cleanText(text);
      if (!value) return;
      const opts = options || {};
      const size = opts.size || 9.4;
      const indent = opts.indent || 0;
      const width = contentWidth - indent;
      const lineHeight = size * 1.42;
      font(opts.bold ? "bold" : "normal", size, [42, 42, 42]);
      const lines = doc.splitTextToSize(value, width);
      ensureSpace(lines.length * lineHeight + 7);
      doc.text(lines, marginX + indent, y, { lineHeightFactor: 1.42 });
      y += lines.length * lineHeight + (opts.tight ? 3 : 7);
    }

    function writeBullet(text, numberLabel) {
      const value = cleanText(text);
      if (!value) return;
      const size = 9.3;
      const bulletIndent = 13;
      const textIndent = 22;
      const width = contentWidth - textIndent;
      const lineHeight = size * 1.4;
      font("normal", size, [42, 42, 42]);
      const lines = doc.splitTextToSize(value, width);
      ensureSpace(lines.length * lineHeight + 4);
      doc.text(numberLabel || "•", marginX + bulletIndent, y);
      doc.text(lines, marginX + textIndent, y, { lineHeightFactor: 1.4 });
      y += lines.length * lineHeight + 4;
    }

    function writeReferenceCard(imageData, name, details) {
      const photoMaxWidth = 50;
      const photoMaxHeight = 62;
      const gap = 11;
      const hasImage = Boolean(imageData);
      const textX = marginX + (hasImage ? photoMaxWidth + gap : 0);
      const textWidth = contentWidth - (hasImage ? photoMaxWidth + gap : 0);
      const titleSize = 10.2;
      const bodySize = 8.9;
      const titleLineHeight = 13;
      const bodyLineHeight = 11.5;

      font("bold", titleSize, [48, 52, 56]);
      const titleLines = doc.splitTextToSize(cleanText(name), textWidth);
      const wrappedDetails = [];
      details.forEach(function (detail) {
        const value = cleanText(detail);
        if (!value) return;
        font("normal", bodySize, [55, 58, 61]);
        wrappedDetails.push(doc.splitTextToSize(value, textWidth));
      });

      let textHeight = titleLines.length * titleLineHeight + 3;
      wrappedDetails.forEach(function (lines) {
        textHeight += lines.length * bodyLineHeight + 2;
      });
      const cardHeight = Math.max(hasImage ? photoMaxHeight : 0, textHeight) + 14;
      ensureSpace(cardHeight + 6);

      const top = y;
      doc.setDrawColor(229, 231, 233);
      doc.roundedRect(marginX, top, contentWidth, cardHeight, 4, 4, "S");

      if (hasImage) {
        const fit = getImageFit(imageData, photoMaxWidth, photoMaxHeight);
        const imageTop = top + 7 + Math.max(0, (photoMaxHeight - fit.height) / 2);
        addImageFit(imageData, marginX + 7, imageTop, photoMaxWidth, photoMaxHeight);
      }

      let textY = top + 15;
      font("bold", titleSize, [48, 52, 56]);
      doc.text(titleLines, textX + 7, textY);
      textY += titleLines.length * titleLineHeight + 2;

      wrappedDetails.forEach(function (lines) {
        font("normal", bodySize, [55, 58, 61]);
        doc.text(lines, textX + 7, textY, { lineHeightFactor: 1.28 });
        textY += lines.length * bodyLineHeight + 2;
      });

      y = top + cardHeight + 7;
    }

    function writeRule() {
      ensureSpace(12);
      y += 2;
      doc.setDrawColor(225, 225, 225);
      doc.line(marginX, y, pageWidth - marginX, y);
      y += 10;
    }

    function writeGap(points) {
      ensureSpace(points || 6);
      y += points || 6;
    }

    function addPageNumbers() {
      const total = doc.getNumberOfPages();
      for (let i = 1; i <= total; i += 1) {
        doc.setPage(i);
        font("normal", 8, [120, 120, 120]);
        doc.text("Page " + i + " of " + total, pageWidth / 2, pageHeight - 20, { align: "center" });
      }
    }

    return {
      doc: doc,
      writeHeader: writeHeader,
      writeSectionHeading: writeSectionHeading,
      writeSubHeading: writeSubHeading,
      writeParagraph: writeParagraph,
      writeBullet: writeBullet,
      writeReferenceCard: writeReferenceCard,
      writeRule: writeRule,
      writeGap: writeGap,
      addPageNumbers: addPageNumbers
    };
  }

  function shouldSkip(node) {
    if (!node || node.nodeType !== 1) return true;
    if (node.classList.contains("no-pdf")) return true;
    return ["DETAILS", "PRE", "SCRIPT", "STYLE", "IMG", "NOSCRIPT"].includes(node.tagName);
  }

  async function processReferenceCard(node, writer) {
    const image = node.querySelector("img");
    const heading = node.querySelector("h3");
    const detailNodes = Array.from(node.querySelectorAll("p")).filter(function (item) {
      return !item.classList.contains("no-pdf");
    });
    const imageData = image ? await loadImageData(image.getAttribute("src") || image.src) : null;
    writer.writeReferenceCard(
      imageData,
      heading ? nodeText(heading) : "Reference",
      detailNodes.map(function (item) { return nodeText(item); })
    );
  }


  function processAcademicServiceRow(node, writer) {
    const label = node.querySelector(".academic-service-label");
    const content = node.querySelector(".academic-service-content");

    if (label) {
      writer.writeParagraph(nodeText(label), { bold: true, tight: true, size: 9.6 });
    }

    if (content) {
      Array.from(content.children).forEach(function (item) {
        const value = nodeText(item);
        if (value) writer.writeParagraph(value, { tight: true, size: 9.2, indent: 10 });
      });
      writer.writeGap(4);
    }
  }

  async function processElement(node, writer) {
    if (shouldSkip(node)) return;

    const tag = node.tagName;

    if (node.classList.contains("cv-section-title")) return;

    if (node.classList.contains("reference-card")) {
      await processReferenceCard(node, writer);
      return;
    }

    if (node.classList.contains("academic-service-row")) {
      processAcademicServiceRow(node, writer);
      return;
    }

    if (tag === "H1" || tag === "H2" || tag === "H3" || tag === "H4") {
      writer.writeSubHeading(nodeText(node), tag === "H2" ? 2 : 3);
      return;
    }

    if (tag === "P") {
      writer.writeParagraph(nodeText(node));
      return;
    }

    if (tag === "UL" || tag === "OL") {
      const items = Array.from(node.children).filter(function (child) {
        return child.tagName === "LI";
      });
      items.forEach(function (item, index) {
        writer.writeBullet(nodeText(item), tag === "OL" ? String(index + 1) + "." : "•");
      });
      writer.writeGap(2);
      return;
    }

    if (tag === "HR") {
      writer.writeRule();
      return;
    }

    const children = Array.from(node.children);
    for (let i = 0; i < children.length; i += 1) {
      await processElement(children[i], writer);
    }
  }

  async function buildPdfFromCurrentPage(jsPDF) {
    const source = await getOriginalCvSource();
    if (!source) throw new Error("The current page does not contain CV content.");

    const writer = createPdfWriter(jsPDF);
    const header = source.querySelector(".cv-pdf-header");

    let name = "Muhammad Sher Afgan";
    let bio = "";
    let contact = "";
    let profileImage = null;

    if (header) {
      const headerName = header.querySelector("h1");
      const headerParagraphs = header.querySelectorAll("p");
      const profileNode = header.querySelector(".cv-pdf-profile");
      if (headerName) name = nodeText(headerName);
      if (headerParagraphs[0]) bio = nodeText(headerParagraphs[0]);
      if (headerParagraphs[1]) contact = nodeText(headerParagraphs[1]);
      if (profileNode) profileImage = await loadImageData(profileNode.getAttribute("src") || profileNode.src);
    }

    /* Fallback to the visible author portrait if the hidden PDF header image
       could not be loaded for any reason. */
    if (!profileImage) {
      const visibleProfile = document.querySelector(".author__avatar img, .author__avatar-image img, img.author__avatar");
      if (visibleProfile) profileImage = await loadImageData(visibleProfile.currentSrc || visibleProfile.src);
    }

    writer.writeHeader(name, bio, contact, profileImage);

    const sections = Array.from(source.children).filter(function (section) {
      return section.classList && section.classList.contains("cv-section") && !section.classList.contains("no-pdf");
    });

    for (let s = 0; s < sections.length; s += 1) {
      const section = sections[s];
      const titleNode = Array.from(section.children).find(function (child) {
        return child.classList && child.classList.contains("cv-section-title");
      });
      const title = titleNode ? nodeText(titleNode) : (section.getAttribute("data-pdf-title") || "");
      if (title) writer.writeSectionHeading(title);

      const children = Array.from(section.children);
      for (let i = 0; i < children.length; i += 1) {
        const child = children[i];
        if (child === titleNode) continue;
        await processElement(child, writer);
      }

      writer.writeGap(8);
    }

    writer.addPageNumbers();
    return writer.doc;
  }

  async function generateCurrentCvPdf() {
    if (generating) return;
    if (!document.getElementById("cv-content")) {
      window.location.href = "/#download-cv";
      return;
    }

    generating = true;
    setStatus("Generating the English CV PDF…");

    try {
      const jsPDF = await loadJsPdf();
      const doc = await buildPdfFromCurrentPage(jsPDF);
      doc.setProperties({
        title: "Muhammad Sher Afgan - Curriculum Vitae",
        subject: "Academic Curriculum Vitae",
        author: "Muhammad Sher Afgan"
      });
      doc.save(PDF_FILENAME);
      setStatus("");
    } catch (error) {
      console.error(error);
      setStatus("PDF generation failed. Please refresh the page and try again.");
    } finally {
      generating = false;
    }
  }

  document.addEventListener("click", function (event) {
    const link = event.target.closest('a[href$="#download-cv"]');
    if (!link) return;
    if (!document.getElementById("cv-content")) return;

    event.preventDefault();
    generateCurrentCvPdf();
  });

  if (window.location.hash === "#download-cv" && document.getElementById("cv-content")) {
    window.setTimeout(function () {
      generateCurrentCvPdf();
      if (window.history && window.history.replaceState) {
        window.history.replaceState(null, "", window.location.pathname + window.location.search);
      }
    }, 250);
  }
})();
